INSERT IGNORE INTO platforms (station_id, platform_number, capacity)
SELECT stations.id,
       platform_numbers.platform_number,
       GREATEST(200, 1500 DIV GREATEST(stations.platform_count, 1))
FROM stations
JOIN (
    SELECT 1 AS platform_number UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
    UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8
    UNION ALL SELECT 9 UNION ALL SELECT 10 UNION ALL SELECT 11 UNION ALL SELECT 12
    UNION ALL SELECT 13 UNION ALL SELECT 14 UNION ALL SELECT 15 UNION ALL SELECT 16
    UNION ALL SELECT 17 UNION ALL SELECT 18 UNION ALL SELECT 19 UNION ALL SELECT 20
    UNION ALL SELECT 21 UNION ALL SELECT 22 UNION ALL SELECT 23
) AS platform_numbers
    ON platform_numbers.platform_number <= stations.platform_count;
